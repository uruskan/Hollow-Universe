using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Hollow.NetGen;

public static partial class NetGenerator
{
    // ---------------------------------------------------------------- writing

    private static string Emit(List<string> usings, string ns, List<StructDef> structs, string source)
    {
        var o = new StringBuilder();
        o.Append("// <auto-generated>\n");
        o.Append($"// Written by tools/Hollow.NetGen from {source}. Don't edit: change {source}, then run\n");
        o.Append("//     dotnet run --project tools/Hollow.NetGen\n");
        o.Append("// </auto-generated>\n");
        o.Append("#nullable enable\n");
        var allUsings = new SortedSet<string>(usings, System.StringComparer.Ordinal) { "using Hollow.Net.Bits;", "using System;" };
        foreach (string u in allUsings.OrderBy(u => u.StartsWith("using System", System.StringComparison.Ordinal) ? 0 : 1).ThenBy(u => u, System.StringComparer.Ordinal))
        {
            o.Append(u).Append('\n');
        }
        o.Append('\n').Append($"namespace {ns};\n\n");
        o.Append("public static partial class Protocol\n{\n");
        o.Append("    /// <summary>A hash of every message layout: two builds speak the same protocol only if theirs match.</summary>\n");
        o.Append($"    public const ulong SchemaHash = 0x{SchemaHash(structs):X16}UL;\n");
        o.Append("}\n");
        foreach (StructDef def in structs)
        {
            o.Append('\n');
            EmitStruct(o, def);
        }
        return o.ToString();
    }

    private static void EmitStruct(StringBuilder o, StructDef def)
    {
        if (def.Kind == StructKind.Message)
        {
            // A message implements INetMessage<T> (GROUND_SYSTEMS.md §12.4), so a handler registry finds it by its type
            // byte; Read, Write and WriteMessage are the interface's other members. The layout is untouched, so the
            // schema hash is too.
            o.Append($"partial struct {def.Name} : INetMessage<{def.Name}>\n{{\n");
            o.Append($"    public const byte TypeId = {def.Id};\n\n");
            o.Append($"    static byte INetMessage<{def.Name}>.Id => TypeId;\n\n");
            o.Append("    /// <summary>The type byte, then the message.</summary>\n");
            o.Append("    public readonly void WriteMessage(BitWriter w)\n    {\n        w.WriteBits(TypeId, 8);\n        Write(w);\n    }\n\n");
        }
        else
        {
            o.Append($"partial struct {def.Name}\n{{\n");
        }
        o.Append("    public readonly void Write(BitWriter w)\n    {\n");
        foreach (Field f in def.Fields)
        {
            EmitWrite(o, f);
        }
        o.Append("    }\n\n");
        o.Append($"    public static {def.Name} Read(BitReader r)\n    {{\n        var v = new {def.Name}();\n");
        foreach (Field f in def.Fields)
        {
            EmitRead(o, f);
        }
        o.Append("        return v;\n    }\n");
        if (def.Kind == StructKind.State)
        {
            o.Append($"\n    /// <summary>Only what differs from <paramref name=\"b\"/>: a bit per field, then the change.</summary>\n");
            o.Append($"    public readonly void WriteDelta(BitWriter w, in {def.Name} b)\n    {{\n");
            foreach (Field f in def.Fields)
            {
                EmitWriteDelta(o, f);
            }
            o.Append("    }\n\n");
            o.Append($"    public static {def.Name} ReadDelta(BitReader r, in {def.Name} b)\n    {{\n        var v = b;\n");
            foreach (Field f in def.Fields)
            {
                EmitReadDelta(o, f);
            }
            o.Append("        return v;\n    }\n\n");
            string same = string.Join(" && ", def.Fields.Select(f => $"{f.Name} == o.{f.Name}"));
            o.Append($"    public readonly bool SameAs(in {def.Name} o) => {same};\n\n");
            o.Append("    /// <summary>The bits <see cref=\"WriteDelta\"/> takes, without writing.</summary>\n");
            o.Append($"    public readonly int DeltaBits(in {def.Name} b)\n    {{\n        int bits = 0;\n");
            foreach (Field f in def.Fields)
            {
                string cost = f.Kind switch
                {
                    FieldKind.Bool => "1",
                    FieldKind.Signed => $"{f.Name} == b.{f.Name} ? 1 : 1 + BitWriter.DeltaBits(unchecked((int){f.Name} - (int)b.{f.Name}))",
                    FieldKind.Angle => $"{f.Name} == b.{f.Name} ? 1 : 1 + BitWriter.DeltaBits((short)unchecked((ushort)({f.Name} - b.{f.Name})))",
                    FieldKind.VarUInt or FieldKind.VarULong => $"{f.Name} == b.{f.Name} ? 1 : 1 + BitWriter.VarUIntBits({f.Name})",
                    _ => $"{f.Name} == b.{f.Name} ? 1 : {1 + FullBits(f)}",
                };
                o.Append($"        bits += {cost};\n");
            }
            o.Append("        return bits;\n    }\n\n");
            string fullCost = string.Join(" + ", def.Fields.Select(f => f.Kind is FieldKind.VarUInt or FieldKind.VarULong
                ? $"BitWriter.VarUIntBits({f.Name})" : FullBits(f).ToString(System.Globalization.CultureInfo.InvariantCulture)));
            o.Append("    /// <summary>The exact bits <see cref=\"Write\"/> takes for this state, without writing.</summary>\n");
            o.Append($"    public readonly int EncodedBits => {fullCost};\n\n");
            o.Append("    /// <summary>The maximum bits <see cref=\"Write\"/> takes.</summary>\n");
            o.Append($"    public const int FullBits = {def.Fields.Sum(FullBits)};\n");
        }
        o.Append("}\n");
    }

    // Fixed-size fields of a state; VarInt is costed at its largest.
    private static int FullBits(Field f) => f.Kind switch
    {
        FieldKind.VarUInt => 40,
        FieldKind.VarULong => 80,
        _ => f.Bits,
    };

    private static void EmitWrite(StringBuilder o, Field f)
    {
        string n = f.Name;
        switch (f.Kind)
        {
            case FieldKind.Bool:
                Line(o, $"w.WriteBool({n});");
                break;
            case FieldKind.Bits:
            case FieldKind.Angle:
                Line(o, $"w.WriteBits((uint){n}, {f.Bits});");
                break;
            case FieldKind.Bits64:
                Line(o, $"w.WriteBits64({n}, {f.Bits});");
                break;
            case FieldKind.Signed:
                Line(o, $"w.WriteSigned({n}, {f.Bits});");
                break;
            case FieldKind.Signed64:
                Line(o, $"w.WriteSigned64({n}, {f.Bits});");
                break;
            case FieldKind.VarUInt:
                Line(o, $"w.WriteVarUInt({n});");
                break;
            case FieldKind.VarULong:
                Line(o, $"w.WriteVarULong({n});");
                break;
            case FieldKind.Quantized:
                Line(o, $"w.WriteQuantized({n}, {f.Detail}, {f.Bits});");
                break;
            case FieldKind.Float:
                Line(o, $"w.WriteFloat({n});");
                break;
            case FieldKind.Double:
                Line(o, $"w.WriteDouble({n});");
                break;
            case FieldKind.String:
                Line(o, $"w.WriteString({n}, {f.Detail});");
                break;
            case FieldKind.Nested:
                Line(o, $"{n}.Write(w);");
                break;
            case FieldKind.Array:
                Line(o, $"int count{n} = {n} == null ? 0 : Math.Min({n}.Length, {f.Detail});");
                Line(o, $"w.WriteBits((uint)count{n}, {f.Bits});");
                Line(o, $"for (int i = 0; i < count{n}; i++)");
                Line(o, "{");
                Line(o, $"    {n}![i].Write(w);");
                Line(o, "}");
                break;
        }
    }

    private static void EmitRead(StringBuilder o, Field f)
    {
        string n = f.Name;
        switch (f.Kind)
        {
            case FieldKind.Bool:
                Line(o, $"v.{n} = r.ReadBool();");
                break;
            case FieldKind.Bits:
            case FieldKind.Angle:
                Line(o, $"v.{n} = ({f.Type})r.ReadBits({f.Bits});");
                break;
            case FieldKind.Bits64:
                Line(o, $"v.{n} = r.ReadBits64({f.Bits});");
                break;
            case FieldKind.Signed:
                Line(o, $"v.{n} = ({f.Type})r.ReadSigned({f.Bits});");
                break;
            case FieldKind.Signed64:
                Line(o, $"v.{n} = r.ReadSigned64({f.Bits});");
                break;
            case FieldKind.VarUInt:
                Line(o, $"v.{n} = r.ReadVarUInt();");
                break;
            case FieldKind.VarULong:
                Line(o, $"v.{n} = r.ReadVarULong();");
                break;
            case FieldKind.Quantized:
                Line(o, $"v.{n} = r.ReadQuantized({f.Detail}, {f.Bits});");
                break;
            case FieldKind.Float:
                Line(o, $"v.{n} = r.ReadFloat();");
                break;
            case FieldKind.Double:
                Line(o, $"v.{n} = r.ReadDouble();");
                break;
            case FieldKind.String:
                Line(o, $"v.{n} = r.ReadString({f.Detail});");
                break;
            case FieldKind.Nested:
                Line(o, $"v.{n} = {f.Type}.Read(r);");
                break;
            case FieldKind.Array:
                Line(o, $"int count{n} = (int)r.ReadBits({f.Bits});");
                Line(o, $"if (count{n} > {f.Detail})");
                Line(o, "{");
                Line(o, "    r.Fail();");
                Line(o, $"    count{n} = 0;");
                Line(o, "}");
                Line(o, $"v.{n} = new {f.Type}[count{n}];");
                Line(o, $"for (int i = 0; i < count{n}; i++)");
                Line(o, "{");
                Line(o, $"    v.{n}[i] = {f.Type}.Read(r);");
                Line(o, "}");
                break;
        }
    }

    private static void EmitWriteDelta(StringBuilder o, Field f)
    {
        string n = f.Name;
        switch (f.Kind)
        {
            case FieldKind.Bool:
                Line(o, $"w.WriteBool({n});");
                return;
            case FieldKind.Signed:
                Line(o, $"if ({n} != b.{n})");
                Line(o, "{");
                Line(o, "    w.WriteBool(true);");
                Line(o, $"    w.WriteDelta(unchecked((int){n} - (int)b.{n}));");
                Line(o, "}");
                break;
            case FieldKind.Angle:
                Line(o, $"if ({n} != b.{n})");
                Line(o, "{");
                Line(o, "    w.WriteBool(true);");
                Line(o, $"    w.WriteDelta((short)unchecked((ushort)({n} - b.{n})));");
                Line(o, "}");
                break;
            default:
                Line(o, $"if ({n} != b.{n})");
                Line(o, "{");
                Line(o, "    w.WriteBool(true);");
                var inner = new StringBuilder();
                EmitWrite(inner, f);
                o.Append(Indent(inner.ToString()));
                Line(o, "}");
                break;
        }
        Line(o, "else");
        Line(o, "{");
        Line(o, "    w.WriteBool(false);");
        Line(o, "}");
    }

    private static void EmitReadDelta(StringBuilder o, Field f)
    {
        string n = f.Name;
        switch (f.Kind)
        {
            case FieldKind.Bool:
                Line(o, $"v.{n} = r.ReadBool();");
                return;
            case FieldKind.Signed:
                Line(o, "if (r.ReadBool())");
                Line(o, "{");
                Line(o, $"    v.{n} = unchecked(({f.Type})((int)b.{n} + r.ReadDelta()));");
                Line(o, "}");
                return;
            case FieldKind.Angle:
                Line(o, "if (r.ReadBool())");
                Line(o, "{");
                Line(o, $"    v.{n} = unchecked((ushort)(b.{n} + r.ReadDelta()));");
                Line(o, "}");
                return;
            default:
                Line(o, "if (r.ReadBool())");
                Line(o, "{");
                var inner = new StringBuilder();
                EmitRead(inner, f);
                o.Append(Indent(inner.ToString()));
                Line(o, "}");
                return;
        }
    }

    private static void Line(StringBuilder o, string text) => o.Append("        ").Append(text).Append('\n');

    private static string Indent(string lines) =>
        string.Concat(lines.Split('\n').Where(l => l.Length > 0).Select(l => "    " + l + "\n"));

    // FNV-1a over a canonical description of every layout.
    private static ulong SchemaHash(List<StructDef> structs)
    {
        var text = new StringBuilder();
        foreach (StructDef def in structs)
        {
            text.Append(CultureInfo.InvariantCulture, $"{def.Kind}:{def.Name}:{def.Id}{{");
            foreach (Field f in def.Fields)
            {
                text.Append(CultureInfo.InvariantCulture, $"{f.Name}:{f.Type}:{f.Kind}:{f.Bits}:{f.Detail};");
            }
            text.Append('}');
        }
        ulong hash = 14695981039346656037UL;
        foreach (char c in text.ToString())
        {
            hash ^= c;
            hash *= 1099511628211UL;
        }
        return hash;
    }
}
