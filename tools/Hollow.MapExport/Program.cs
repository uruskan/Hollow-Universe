/// <summary>
/// Exports read-only snapshots of the real generator for the galaxy-map UX prototypes in
/// prototypes/map-ux (see prototypes/map-ux/data/README.md). Each output is a plain script that sets one
/// global, so a prototype opened from disk (file://) can load it with &lt;script src&gt;.
///
/// Usage (from the repository root): dotnet run --project tools/Hollow.MapExport -c Release [-- outputDir]
/// </summary>
internal static class Program
{
    private static int Main(string[] args)
    {
        if (!BitConverter.IsLittleEndian)
        {
            Console.Error.WriteLine("The base64 arrays are written little-endian; run this on a little-endian machine.");
            return 1;
        }
        var clock = Stopwatch.StartNew();
        string root = FindRoot();
        string outDir = args.Length > 0
            ? Path.GetFullPath(args[0])
            : Path.Combine(root, "prototypes", "map-ux", "data");
        Directory.CreateDirectory(outDir);

        string cataloguePath = Path.Combine(root, "game", "data", "catalog", "hyg41.bin.gz");
        StarCatalogue catalogue = StarCatalogue.Load(cataloguePath);
        var galaxy = new HollowGalaxy(catalogue);
        Console.WriteLine($"Catalogue: {catalogue.Stars.Count} stars ({clock.Elapsed.TotalSeconds:F1} s)");

        LocalData local = LocalExport.Build(galaxy);
        Console.WriteLine($"Local: {local.Systems.Count} systems within {LocalExport.Radius} ly " +
            $"({local.BodyListCount} with body lists) ({clock.Elapsed.TotalSeconds:F1} s)");
        LocalExport.Write(Path.Combine(outDir, "local.js"), galaxy, local);

        GalaxyExport.Write(Path.Combine(outDir, "galaxy.js"), galaxy);
        Console.WriteLine($"Galaxy sample written ({clock.Elapsed.TotalSeconds:F1} s)");

        MockExport.Write(Path.Combine(outDir, "mock.js"), local);
        Console.WriteLine($"Mock layer written ({clock.Elapsed.TotalSeconds:F1} s)");

        foreach (string name in new[] { "local.js", "galaxy.js", "mock.js" })
        {
            var info = new FileInfo(Path.Combine(outDir, name));
            Console.WriteLine($"  {name}: {info.Length / 1024.0 / 1024.0:F2} MB");
        }
        return 0;
    }

    private static string FindRoot()
    {
        string? dir = Directory.GetCurrentDirectory();
        while (dir != null)
        {
            if (File.Exists(Path.Combine(dir, "HollowUniverse.sln")))
            {
                return dir;
            }
            dir = Path.GetDirectoryName(dir);
        }
        throw new InvalidOperationException("Run from inside the repository (HollowUniverse.sln not found).");
    }
}

/// <summary>Small helpers shared by the exporters.</summary>
internal static class Js
{
    /// <summary>Writes "window.NAME = {json};" with a header comment. Non-ASCII is escaped, so the file is ASCII.</summary>
    public static void WriteGlobal(string path, string global, string summary, Action<Utf8JsonWriter> body)
    {
        using FileStream fs = File.Create(path);
        byte[] head = Encoding.ASCII.GetBytes(
            $"// {summary}\n" +
            "// Generated by tools/Hollow.MapExport from the real Hollow generator. Do not edit; regenerate (README.md).\n" +
            $"window.{global} = ");
        fs.Write(head);
        using (var w = new Utf8JsonWriter(fs, new JsonWriterOptions { Indented = false }))
        {
            body(w);
        }
        fs.Write(";\n"u8);
    }

    public static double Round(double value, int decimals) =>
        Math.Round(value, decimals, MidpointRounding.AwayFromZero);

    /// <summary>Rounds to a number of significant digits.</summary>
    public static double Sig(double value, int digits)
    {
        if (value == 0 || !double.IsFinite(value))
        {
            return 0;
        }
        return double.Parse(value.ToString("G" + digits, CultureInfo.InvariantCulture), CultureInfo.InvariantCulture);
    }

    public static string Hex(ulong value) => "0x" + value.ToString("X16", CultureInfo.InvariantCulture);

    public static void Number(this Utf8JsonWriter w, string name, double value)
    {
        w.WritePropertyName(name);
        w.WriteNumberValue(value);
    }
}

/// <summary>
/// The star colours of the Godot maps (game/scripts/Common/StarColors.cs), copied here because tools must not
/// reference Godot. Keep the two in step.
/// </summary>
internal static class StarColours
{
    private static readonly (float T, float R, float G, float B)[] Ramp =
    {
        (1000, 0.80f, 0.28f, 0.34f),
        (2000, 1.00f, 0.38f, 0.16f),
        (3000, 1.00f, 0.56f, 0.30f),
        (4000, 1.00f, 0.72f, 0.47f),
        (5000, 1.00f, 0.86f, 0.70f),
        (5800, 1.00f, 0.95f, 0.87f),
        (6600, 0.97f, 0.97f, 1.00f),
        (8000, 0.83f, 0.88f, 1.00f),
        (10000, 0.73f, 0.80f, 1.00f),
        (20000, 0.63f, 0.72f, 1.00f),
        (40000, 0.58f, 0.68f, 1.00f),
    };

    public static (float R, float G, float B) FromTemperature(float kelvin)
    {
        if (kelvin <= Ramp[0].T)
        {
            return (Ramp[0].R, Ramp[0].G, Ramp[0].B);
        }
        for (int i = 1; i < Ramp.Length; i++)
        {
            if (kelvin <= Ramp[i].T)
            {
                float t = (kelvin - Ramp[i - 1].T) / (Ramp[i].T - Ramp[i - 1].T);
                return (Lerp(Ramp[i - 1].R, Ramp[i].R, t), Lerp(Ramp[i - 1].G, Ramp[i].G, t),
                    Lerp(Ramp[i - 1].B, Ramp[i].B, t));
            }
        }
        return (Ramp[^1].R, Ramp[^1].G, Ramp[^1].B);
    }

    public static (float R, float G, float B) For(StarClass starClass, float temperature) => starClass.Kind switch
    {
        StarKind.BlackHole => (0.62f, 0.45f, 1.0f),
        StarKind.NeutronStar => (0.70f, 0.90f, 1.0f),
        StarKind.WolfRayet => (0.65f, 0.80f, 1.0f),
        StarKind.CarbonStar => (1.0f, 0.42f, 0.22f),
        _ => FromTemperature(temperature),
    };

    /// <summary>Magnitude the maps draw with: objects that emit no visible light still get a dot.</summary>
    public static float DisplayMagnitude(StarClass starClass, float absoluteMagnitude) => starClass.Kind switch
    {
        StarKind.BlackHole or StarKind.NeutronStar => 11.5f,
        _ => Math.Min(absoluteMagnitude, 17f),
    };

    public static byte Byte(float c) => (byte)MathF.Round(Math.Clamp(c * 255f, 0f, 255f));

    public static string Hex(StarClass starClass, float temperature)
    {
        (float r, float g, float b) = For(starClass, temperature);
        return $"#{Byte(r):x2}{Byte(g):x2}{Byte(b):x2}";
    }

    /// <summary>Main-sequence O, B, A, F, G, K or M: a star a ship can refuel from.</summary>
    public static bool Scoopable(StarClass starClass) =>
        starClass.Kind == StarKind.MainSequence && starClass.Letter is 'O' or 'B' or 'A' or 'F' or 'G' or 'K' or 'M';

    private static float Lerp(float from, float to, float weight) => from + (to - from) * weight;
}
